"""Writes docs/data.js for the GitHub Pages site. Run: python scripts/build_pages.py"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
os.environ["DEMO_MODE"] = "true"        # always build from the saved class data
os.environ["ENABLE_ZSC"] = "false"
os.chdir(ROOT)

from buffalo import analytics  # noqa: E402
import app as A  # noqa: E402

focus = A.SNAPS[-1]
th = 0.10

# EC 1: top entities
ents = analytics.entity_summary(A.E_ALL).head(12)

# EC 2: echo per snapshot and category
ec = A.ECHO.dropna(subset=["echo"])
echo_overall = ec.groupby("snapshot")["echo"].mean().round(3)
echo_by_cat = ec[ec["snapshot"] == focus].groupby("category")["echo"].mean().round(3).sort_values()
deja = ec[ec["snapshot"] == focus].sort_values("echo", ascending=False).head(3)

# EC 3: audit
audit = A.AUDITS[focus]
cov = analytics.coverage_by_category(audit["heads"], th, A.CATS)
weak = audit["sents"].head(3)

# Opinion map
arts = analytics.unique_articles(A.DF[A.DF["snapshot"] == focus])

data = {
    "focus": A.nice_date(focus), "n_headlines": int(A.DF["uid"].nunique()), "n_snapshots": len(A.SNAPS),
    "snapshots": [A.nice_date(s) for s in A.SNAPS], "cat_colors": A.CAT_COLORS,
    "entities": {"name": list(ents["entity"]), "mentions": [int(x) for x in ents["mentions"]],
                 "polarity": [round(float(x), 3) for x in ents["mean_polarity"]]},
    "echo": {"x": [A.nice_date(s) for s in echo_overall.index], "y": list(echo_overall.values),
             "cats": list(echo_by_cat.index), "cat_y": list(echo_by_cat.values),
             "deja": [{"title": r.title, "echo": round(r.echo, 2), "of": r.echo_of, "when": A.nice_date(r.echo_of_snapshot)}
                      for r in deja.itertuples()]},
    "audit": {"threshold": th, "represented": int((audit["heads"]["similarity"] >= th).sum()),
              "total": int(len(audit["heads"])),
              "cats": list(cov["category"]), "share": [round(float(x) * 100, 1) for x in cov["share"]],
              "missing": list(cov.loc[cov["represented"] == 0, "category"]),
              "weak": [{"sentence": r.sentence, "support": round(r.support, 2)} for r in weak.itertuples()]},
    "opinion": {c: {"x": [round(v, 3) for v in g["polarity"]], "y": [round(v, 3) for v in g["subjectivity"]],
                    "t": list(g["title"])} for c, g in arts.groupby("category")},
}
os.makedirs("docs", exist_ok=True)
with open("docs/data.js", "w", encoding="utf-8") as f:
    f.write("// generated by scripts/build_pages.py from the saved class snapshots\n")
    f.write("window.BT = " + json.dumps(data) + ";\n")
print("wrote docs/data.js:", data["n_headlines"], "headlines,", data["audit"]["represented"], "/", data["audit"]["total"], "represented")
